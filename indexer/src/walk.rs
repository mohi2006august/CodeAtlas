//! Which files get indexed.
//!
//! Generated and vendored code is excluded because it dominates results
//! (CLAUDE.md gotcha), and files that look like they hold secrets never enter
//! the index (SYSTEM_ARCHITECTURE §7). The same rules run in full scans and in
//! git-diff incremental runs so both produce the same index.

use std::path::Path;
use std::sync::LazyLock;

use anyhow::Result;
use ignore::gitignore::{Gitignore, GitignoreBuilder};
use regex::bytes::Regex;

use crate::{git, lang};

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum SkipReason {
    Hidden,
    Vendored,
    Generated,
    Ignored,
    Unsupported,
    TooLarge,
    Binary,
    Minified,
    Secret,
}

impl SkipReason {
    pub fn as_str(self) -> &'static str {
        match self {
            SkipReason::Hidden => "hidden",
            SkipReason::Vendored => "vendored",
            SkipReason::Generated => "generated",
            SkipReason::Ignored => "ignored",
            SkipReason::Unsupported => "unsupported",
            SkipReason::TooLarge => "too_large",
            SkipReason::Binary => "binary",
            SkipReason::Minified => "minified",
            SkipReason::Secret => "secret",
        }
    }
}

const VENDORED_DIRS: &[&str] = &[
    "node_modules", "vendor", "third_party", "third-party", "thirdparty", "bower_components",
    "jspm_packages", "Pods", "Carthage", "site-packages", "venv", "__pycache__", "dist", "target",
    "_build", "deps", "elm-stuff", "generated", "__generated__",
];

const GENERATED_SUFFIXES: &[&str] = &[
    ".min.js", ".min.css", ".bundle.js", "_pb2.py", "_pb2_grpc.py", ".pb.go", ".pb.cc", ".pb.h",
    ".g.dart", ".freezed.dart", ".designer.cs", ".g.cs", "_generated.go", ".gen.go", ".gen.ts",
];

const GENERATED_MARKERS: &[&str] = &[
    "@generated",
    "do not edit",
    "code generated by",
    "auto-generated",
    "autogenerated",
    "automatically generated",
];

const SECRET_STEMS: &[&str] = &["secrets", "secret", "credentials", "credential"];

static SECRET_PATTERNS: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(concat!(
        r"-----BEGIN (?:RSA |EC |DSA |OPENSSH |PGP |ENCRYPTED )?PRIVATE KEY-----",
        r"|\bAKIA[0-9A-Z]{16}\b",
        r"|\bgh[pousr]_[A-Za-z0-9]{36}\b",
        r"|\bgithub_pat_[A-Za-z0-9_]{60,}",
        r"|\bxox[baprs]-[A-Za-z0-9-]{10,}",
        r"|\bsk_live_[0-9a-zA-Z]{24,}",
        r"|\bAIza[0-9A-Za-z_\-]{35}\b",
    ))
    .expect("secret patterns compile")
});

pub struct Filter {
    ignore: Gitignore,
    max_file_bytes: u64,
}

impl Filter {
    /// `.codeatlasignore` at the root and `--exclude` globs use gitignore syntax.
    pub fn new(root: &Path, excludes: &[String], max_file_bytes: u64) -> Result<Self> {
        let mut builder = GitignoreBuilder::new(root);
        let custom = root.join(".codeatlasignore");
        if custom.is_file() {
            if let Some(err) = builder.add(&custom) {
                return Err(err.into());
            }
        }
        for pattern in excludes {
            builder.add_line(None, pattern)?;
        }
        Ok(Filter { ignore: builder.build()?, max_file_bytes })
    }

    /// Decide from the path alone (cheap; runs before reading the file).
    pub fn path_reason(&self, rel: &str) -> Option<SkipReason> {
        let parts: Vec<&str> = rel.split('/').collect();
        if parts.iter().any(|p| p.starts_with('.') && *p != "." && *p != "..") {
            return Some(SkipReason::Hidden);
        }
        let dirs = &parts[..parts.len().saturating_sub(1)];
        if dirs.iter().any(|d| VENDORED_DIRS.contains(d)) {
            return Some(SkipReason::Vendored);
        }
        let file = parts.last().copied().unwrap_or("");
        let lower = file.to_ascii_lowercase();
        if GENERATED_SUFFIXES.iter().any(|s| lower.ends_with(&s.to_ascii_lowercase()))
            || lower.contains(".generated.")
        {
            return Some(SkipReason::Generated);
        }
        let stem = lower.split('.').next().unwrap_or("");
        if SECRET_STEMS.contains(&stem) {
            return Some(SkipReason::Secret);
        }
        if self.ignore.matched_path_or_any_parents(rel, false).is_ignore() {
            return Some(SkipReason::Ignored);
        }
        if !lang::is_indexable_path(rel) {
            return Some(SkipReason::Unsupported);
        }
        None
    }

    /// Decide from the contents (size, binary, generated header, minified, secrets).
    pub fn content_reason(&self, bytes: &[u8]) -> Option<SkipReason> {
        if bytes.len() as u64 > self.max_file_bytes {
            return Some(SkipReason::TooLarge);
        }
        if bytes[..bytes.len().min(8192)].contains(&0) {
            return Some(SkipReason::Binary);
        }
        let head = String::from_utf8_lossy(&bytes[..bytes.len().min(1024)]).to_ascii_lowercase();
        if GENERATED_MARKERS.iter().any(|m| head.contains(m)) {
            return Some(SkipReason::Generated);
        }
        if looks_minified(bytes) {
            return Some(SkipReason::Minified);
        }
        if SECRET_PATTERNS.is_match(bytes) {
            return Some(SkipReason::Secret);
        }
        None
    }
}

fn looks_minified(bytes: &[u8]) -> bool {
    let sample = &bytes[..bytes.len().min(64 * 1024)];
    let lines = sample.split(|b| *b == b'\n');
    let (mut count, mut longest) = (0usize, 0usize);
    for line in lines {
        count += 1;
        longest = longest.max(line.len());
    }
    longest > 5000 || (sample.len() > 4096 && sample.len() / count.max(1) > 300)
}

/// Candidate files: git's view (tracked + untracked, not ignored) inside a
/// repository, otherwise a gitignore-aware directory walk.
pub fn list_files(root: &Path) -> Result<Vec<String>> {
    if git::is_repo(root) {
        return git::ls_files(root);
    }
    let mut out = Vec::new();
    let walker = ignore::WalkBuilder::new(root)
        .hidden(true)
        .require_git(false)
        .add_custom_ignore_filename(".codeatlasignore")
        .build();
    for entry in walker.flatten() {
        if entry.file_type().is_some_and(|t| t.is_file()) {
            if let Ok(rel) = entry.path().strip_prefix(root) {
                out.push(rel.to_string_lossy().replace('\\', "/"));
            }
        }
    }
    out.sort();
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn filter() -> Filter {
        Filter::new(Path::new("."), &["legacy/**".to_string()], 1 << 20).unwrap()
    }

    #[test]
    fn path_rules() {
        let f = filter();
        assert_eq!(f.path_reason("billing/retry.py"), None);
        assert_eq!(f.path_reason("web/node_modules/x/index.js"), Some(SkipReason::Vendored));
        assert_eq!(f.path_reason(".github/scripts/x.py"), Some(SkipReason::Hidden));
        assert_eq!(f.path_reason("api/user_pb2.py"), Some(SkipReason::Generated));
        assert_eq!(f.path_reason("static/app.min.js"), Some(SkipReason::Generated));
        assert_eq!(f.path_reason("config/secrets.py"), Some(SkipReason::Secret));
        assert_eq!(f.path_reason("legacy/old.py"), Some(SkipReason::Ignored));
        assert_eq!(f.path_reason("README.md"), Some(SkipReason::Unsupported));
    }

    #[test]
    fn content_rules() {
        let f = filter();
        assert_eq!(f.content_reason(b"def f():\n    return 1\n"), None);
        assert_eq!(f.content_reason(b"// Code generated by protoc. DO NOT EDIT.\n"), Some(SkipReason::Generated));
        assert_eq!(f.content_reason(b"\0\x01\x02"), Some(SkipReason::Binary));
        let minified = format!("var a={};", "x".repeat(6000));
        assert_eq!(f.content_reason(minified.as_bytes()), Some(SkipReason::Minified));
        // Built at runtime so the repository itself never contains a key-shaped string.
        let key = format!("AWS_KEY = '{}{}'\n", "AKIA", "Q".repeat(16));
        assert_eq!(f.content_reason(key.as_bytes()), Some(SkipReason::Secret));
        let pem = format!("-----BEGIN {} KEY-----\n", "PRIVATE");
        assert_eq!(f.content_reason(pem.as_bytes()), Some(SkipReason::Secret));
    }
}
